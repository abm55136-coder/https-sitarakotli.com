export function resolveTranslations(
  lang: string,
  aiOverrides?: Record<string, string>
): TranslationDictionary {
  if (lang === 'ur') {
    return {
      ...translations.en,
      ...translations.ur,
      ...(aiOverrides || {}),
    };
  }
  if (lang === 'en') {
    return translations.en;
  }
  return {
    ...translations.en,
    ...(NATIVE_LANGUAGE_OVERRIDES[lang] || {}),
    ...(aiOverrides || {}),
  };
}

